// Empaqueta la ingesta TypeScript para el worker Node (server/corpus).
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'vite'

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const entry = join(projectRoot, 'src', 'corpus', 'ingestEntry.ts')
const outDir = join(projectRoot, 'server', 'corpus')
const outfile = join(outDir, 'ingest.bundle.mjs')

await mkdir(outDir, { recursive: true })

const result = await build({
  configFile: false,
  root: projectRoot,
  logLevel: 'warn',
  build: {
    ssr: true,
    ssrEmitAssets: false,
    write: false,
    minify: false,
    sourcemap: true,
    target: 'node20',
    rollupOptions: {
      input: entry,
      output: {
        format: 'esm',
        entryFileNames: 'ingest.bundle.mjs',
        codeSplitting: false,
      },
      external: [
        /^node:/,
        'fs',
        'path',
        'url',
        'fs/promises',
      ],
    },
  },
})

const outputs = Array.isArray(result) ? result : [result]
const bundle = outputs[0]
if (!bundle || !('output' in bundle)) {
  throw new Error('Vite no generó el bundle del corpus')
}

const entryChunk = bundle.output.find((item) => item.type === 'chunk' && item.isEntry)
if (!entryChunk || entryChunk.type !== 'chunk') {
  throw new Error('No se encontró el chunk de entrada del corpus')
}

const banner = '// Generated by scripts/bundle-corpus.mjs — do not edit.\n'
await writeFile(outfile, banner + entryChunk.code, 'utf8')
if (entryChunk.map) {
  await writeFile(`${outfile}.map`, JSON.stringify(entryChunk.map), 'utf8')
}

console.log(`Corpus ingest bundle → ${outfile}`)
